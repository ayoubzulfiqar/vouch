use std::{collections::BTreeMap, io::Write, net::Ipv4Addr, path::PathBuf, time::Duration};

use tokio::net::TcpStream;

use crate::{
    auth::discovery::resolve_binary,
    cli::{InitArgs, token::generate_random_token},
    config::GatewayConfig,
    error::{GatewayError, Result},
    persistence::write_atomic_0600,
};

/// Known local AI agent CLIs scanned by `vouch init`.
const KNOWN_CLIS: &[(&str, &str, &[&str], bool)] = &[
    // (binary, backend_id, args, stdin)
    (
        "hermes",
        "hermes-cli",
        &["chat", "--plain", "-q", "{prompt}"],
        false,
    ),
    ("opencode", "opencode-cli", &["run", "{prompt}"], false),
    ("kilocode", "kilocode-cli", &["--auto", "{prompt}"], false),
    ("claude", "claude-cli", &["-p", "{prompt}"], false),
    ("codex", "codex-cli", &["exec", "{prompt}"], false),
    ("gemini", "gemini-cli", &["-p", "{prompt}"], false),
];

const KNOWN_HTTP_DAEMONS: &[(&str, &str, u16, &str)] = &[
    // (backend_id, host, port, health_path)
    ("hermes-http", "127.0.0.1", 8645, "/health"),
    ("opencode-http", "127.0.0.1", 4096, "/global/health"),
];

/// Scan the host for authenticated CLIs & local daemons and emit a validated `vouch.toml`.
pub async fn run(args: &InitArgs) -> Result<()> {
    if args.output.exists() && !args.force {
        return Err(GatewayError::Config(format!(
            "refusing to overwrite existing {}; re-run with --force to replace",
            args.output.display()
        )));
    }

    let summary = generate_config(args.docker_bridge).await?;
    // Guarantee the scaffolded file parses cleanly under `deny_unknown_fields`.
    GatewayConfig::from_toml_str(&summary.toml)?;
    write_atomic_0600(&args.output, summary.toml.as_bytes())?;

    let mut stdout = std::io::stdout().lock();
    writeln!(stdout, "wrote {}", args.output.display())?;
    writeln!(stdout, "listen: {}", summary.tcp_listen)?;
    writeln!(
        stdout,
        "backends ({}): {}",
        summary.backends.len(),
        summary.backends.join(", ")
    )?;
    if summary.used_fallback_stub {
        writeln!(
            stdout,
            "note: no local agent CLIs/daemons detected; added a starter `sh -c cat` backend placeholder"
        )?;
    }
    writeln!(stdout, "token: {} (mode 0600)", summary.token)?;
    Ok(())
}

/// Generated scaffold metadata and validated TOML document.
#[derive(Debug, Clone)]
pub struct InitScaffold {
    /// Complete validated TOML content.
    pub toml: String,
    /// Selected `server.tcp_listen` address.
    pub tcp_listen: String,
    /// Generated virtual bearer credential.
    pub token: String,
    /// Configured backend identifiers.
    pub backends: Vec<String>,
    /// True if no host CLIs/daemons were detected and a placeholder backend was emitted.
    pub used_fallback_stub: bool,
}

/// Build an initialized `vouch.toml` document without writing to disk.
pub async fn generate_config(docker_bridge: bool) -> Result<InitScaffold> {
    let extra_dirs = extra_user_bin_dirs();
    let mut detected_clis: Vec<(&str, PathBuf, &[&str], bool)> = Vec::new();
    for &(bin, backend_id, args, stdin) in KNOWN_CLIS {
        if let Some(path) = find_cli_binary(bin, &extra_dirs) {
            detected_clis.push((backend_id, path, args, stdin));
        }
    }

    let mut detected_http: Vec<(&str, String, &str)> = Vec::new();
    for &(backend_id, host, port, health_path) in KNOWN_HTTP_DAEMONS {
        if tcp_probe(host, port).await {
            detected_http.push((backend_id, format!("http://{host}:{port}"), health_path));
        }
    }

    let listen_ip = if docker_bridge {
        detect_docker0_ipv4().unwrap_or(Ipv4Addr::new(172, 17, 0, 1))
    } else {
        Ipv4Addr::LOCALHOST
    };
    let tcp_listen = format!("{listen_ip}:8080");
    let token = generate_random_token()?;

    let mut out = String::new();
    out.push_str("# Generated by `vouch init`\n\n");
    out.push_str("[server]\n");
    out.push_str(&format!("tcp_listen = {:?}\n", tcp_listen));
    out.push_str("enable_ui = true\n\n");

    let mut backend_ids: Vec<String> = Vec::new();
    let mut used_fallback_stub = false;

    for (id, base_url, health_path) in &detected_http {
        backend_ids.push((*id).to_string());
        out.push_str("[[backends]]\n");
        out.push_str(&format!("id = {:?}\n", id));
        out.push_str("kind = \"http\"\n");
        out.push_str(&format!("base_url = {:?}\n", base_url));
        out.push_str(&format!("health_path = {:?}\n", health_path));
        out.push_str("max_concurrency = 4\n\n");
    }

    for (id, path, args, stdin) in &detected_clis {
        backend_ids.push((*id).to_string());
        out.push_str("[[backends]]\n");
        out.push_str(&format!("id = {:?}\n", id));
        out.push_str("kind = \"cli\"\n");
        out.push_str(&format!("command = {:?}\n", path.display().to_string()));
        let rendered_args: Vec<String> = args.iter().map(|a| format!("{a:?}")).collect();
        out.push_str(&format!("args = [{}]\n", rendered_args.join(", ")));
        out.push_str(&format!("stdin = {stdin}\n"));
        out.push_str("read_mode = \"chunk\"\n");
        out.push_str("max_concurrency = 2\n\n");
    }

    if backend_ids.is_empty() {
        used_fallback_stub = true;
        backend_ids.push("starter-cli".into());
        out.push_str("[[backends]]\n");
        out.push_str("id = \"starter-cli\"\n");
        out.push_str("kind = \"cli\"\n");
        out.push_str("command = \"sh\"\n");
        out.push_str("args = [\"-c\", \"cat\"]\n");
        out.push_str("stdin = true\n");
        out.push_str("read_mode = \"chunk\"\n\n");
    }

    let first = &backend_ids[0];
    let chain_toml: Vec<String> = backend_ids.iter().map(|id| format!("{id:?}")).collect();

    out.push_str("[defaults]\n");
    out.push_str("model = \"coding/default\"\n");
    out.push_str("max_session_entries = 10000\n\n");

    out.push_str("[routes]\n");
    out.push_str(&format!(
        "\"coding/default\" = [{}]\n",
        chain_toml.join(", ")
    ));
    out.push_str(&format!("\"fast/default\" = [{first:?}]\n\n"));

    out.push_str("[aliases]\n");
    out.push_str("\"gpt-4o\" = \"coding/default\"\n");
    out.push_str("\"default\" = \"coding/default\"\n\n");

    out.push_str("[[tokens]]\n");
    out.push_str("name = \"default-client\"\n");
    out.push_str(&format!("token = {:?}\n", token));
    out.push_str("# daily_token_budget = 2000000\n");

    // Ensure consistent internal map usage doesn't trigger unused warnings
    let _ = BTreeMap::<String, String>::new();

    Ok(InitScaffold {
        toml: out,
        tcp_listen,
        token,
        backends: backend_ids,
        used_fallback_stub,
    })
}

fn extra_user_bin_dirs() -> Vec<PathBuf> {
    let Some(home) = std::env::var_os("HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("USERPROFILE").map(PathBuf::from))
    else {
        return Vec::new();
    };
    [".local/bin", ".opencode/bin", ".npm-global/bin"]
        .into_iter()
        .map(|rel| home.join(rel))
        .collect()
}

/// Resolve `name` via `$PATH` first, then `~/.local/bin`, `~/.opencode/bin`, and `~/.npm-global/bin`.
pub fn find_cli_binary(name: &str, extra_dirs: &[PathBuf]) -> Option<PathBuf> {
    if let Some(found) = resolve_binary(name) {
        return Some(found);
    }
    for dir in extra_dirs {
        let candidate = dir.join(name);
        if candidate.is_file() {
            return resolve_binary(&candidate.display().to_string());
        }
    }
    None
}

async fn tcp_probe(host: &str, port: u16) -> bool {
    tokio::time::timeout(Duration::from_millis(250), TcpStream::connect((host, port)))
        .await
        .is_ok_and(|res| res.is_ok())
}

/// Detect the IPv4 address bound to Linux `docker0` if present.
pub fn detect_docker0_ipv4() -> Option<Ipv4Addr> {
    let output = std::process::Command::new("ip")
        .args(["-4", "-o", "addr", "show", "dev", "docker0"])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&output.stdout);
    parse_ip_addr_show_ipv4(&text)
}

fn parse_ip_addr_show_ipv4(text: &str) -> Option<Ipv4Addr> {
    // Example line: "4: docker0    inet 172.17.0.1/16 brd 172.17.255.255 scope global docker0"
    let mut tokens = text.split_whitespace();
    while let Some(tok) = tokens.next() {
        if tok == "inet"
            && let Some(cidr) = tokens.next()
        {
            let ip_part = cidr.split('/').next().unwrap_or(cidr);
            if let Ok(ip) = ip_part.parse::<Ipv4Addr>() {
                return Some(ip);
            }
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_ip_addr_output_for_docker0() {
        let sample = "4: docker0    inet 172.17.0.1/16 brd 172.17.255.255 scope global docker0\n";
        assert_eq!(
            parse_ip_addr_show_ipv4(sample),
            Some(Ipv4Addr::new(172, 17, 0, 1))
        );
        assert_eq!(parse_ip_addr_show_ipv4(""), None);
    }

    #[tokio::test]
    async fn generated_scaffold_validates_against_strict_schema() {
        let scaffold = generate_config(false).await.expect("scaffold");
        let parsed = GatewayConfig::from_toml_str(&scaffold.toml).expect("valid config");
        assert!(parsed.routes.contains_key("coding/default"));
        assert!(scaffold.token.starts_with("vouch_live_"));
    }
}
